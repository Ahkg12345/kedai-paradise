CREATE OR REPLACE FUNCTION public.generate_menu_code()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_word text;
  v_prefix text;
  v_next integer;
BEGIN
  v_word := pg_catalog.regexp_replace(pg_catalog.split_part(pg_catalog.btrim(NEW.name), ' ', 1), '[^[:alnum:]]', '', 'g');
  v_prefix := pg_catalog.upper(pg_catalog.left(v_word, 3));
  IF v_prefix = '' THEN
    v_prefix := 'MNU';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('menu-code:' || v_prefix));
  SELECT COALESCE(MAX(nullif(pg_catalog.regexp_replace(m.code, '^.*-', ''), '')::integer), 0) + 1
    INTO v_next
    FROM public.menu AS m
    WHERE m.code LIKE 'KP-' || v_prefix || '-%';

  NEW.code := 'KP-' || v_prefix || '-' || pg_catalog.lpad(v_next::text, 2, '0');
  RETURN NEW;
END;
$$;
CREATE TRIGGER menu_generate_code_before_insert
BEFORE INSERT ON public.menu
FOR EACH ROW EXECUTE FUNCTION public.generate_menu_code();

CREATE OR REPLACE FUNCTION public.enforce_menu_group_limit()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_count integer;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.menu_id = OLD.menu_id THEN
    RETURN NEW;
  END IF;

  PERFORM 1 FROM public.menu WHERE menu_id = NEW.menu_id FOR UPDATE;
  IF TG_OP = 'INSERT' THEN
    SELECT count(*) INTO v_count FROM public.menu_modifier_groups WHERE menu_id = NEW.menu_id;
  ELSE
    SELECT count(*) INTO v_count FROM public.menu_modifier_groups WHERE menu_id = NEW.menu_id AND group_id <> OLD.group_id;
  END IF;
  IF v_count >= 5 THEN
    RAISE EXCEPTION 'A menu item can have at most five modifier groups' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER menu_modifier_groups_limit_before_write
BEFORE INSERT OR UPDATE OF menu_id ON public.menu_modifier_groups
FOR EACH ROW EXECUTE FUNCTION public.enforce_menu_group_limit();

CREATE OR REPLACE FUNCTION public.enforce_modifier_item_limit()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_count integer;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.group_id = OLD.group_id THEN
    RETURN NEW;
  END IF;

  PERFORM 1 FROM public.menu_modifier_groups WHERE group_id = NEW.group_id FOR UPDATE;
  IF TG_OP = 'INSERT' THEN
    SELECT count(*) INTO v_count FROM public.menu_modifier_items WHERE group_id = NEW.group_id;
  ELSE
    SELECT count(*) INTO v_count FROM public.menu_modifier_items WHERE group_id = NEW.group_id AND modifier_id <> OLD.modifier_id;
  END IF;
  IF v_count >= 10 THEN
    RAISE EXCEPTION 'A modifier group can have at most ten items' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER menu_modifier_items_limit_before_write
BEFORE INSERT OR UPDATE OF group_id ON public.menu_modifier_items
FOR EACH ROW EXECUTE FUNCTION public.enforce_modifier_item_limit();

