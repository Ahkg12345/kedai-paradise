CREATE TABLE public.transactions (
  transaction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no integer NOT NULL,
  date timestamptz NOT NULL DEFAULT now(),
  order_date date NOT NULL,
  table_no varchar(10) NOT NULL,
  method public.payment_method NOT NULL,
  total integer NOT NULL,
  paid integer NOT NULL,
  change_due integer NOT NULL DEFAULT 0,
  status public.transaction_status NOT NULL DEFAULT 'processing',
  completed_at timestamptz,
  duration_seconds integer,
  total_cost integer NOT NULL DEFAULT 0,
  gross_profit integer NOT NULL DEFAULT 0,
  alloc_restock integer NOT NULL DEFAULT 0,
  alloc_operating integer NOT NULL DEFAULT 0,
  alloc_profit integer NOT NULL DEFAULT 0,
