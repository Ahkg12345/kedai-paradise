        OR ((SELECT public.current_user_role()) = 'cashier' AND t.order_date = pg_catalog.timezone('Asia/Jakarta', now())::date)
      )
  )
$$;

CREATE OR REPLACE FUNCTION public.check_login_lock(p_username text, p_ip_address text)
RETURNS TABLE (is_locked boolean, retry_after_seconds integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_now timestamptz := pg_catalog.clock_timestamp();
  v_lock_until timestamptz;
BEGIN
  IF p_username IS NULL OR p_username !~ '^[a-z0-9_]{3,30}$' OR p_ip_address IS NULL OR pg_catalog.length(p_ip_address) > 45 THEN
    RAISE EXCEPTION 'Invalid login lock parameters' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  SELECT pg_catalog.max(bucket.oldest_attempt + interval '15 minutes')
    INTO v_lock_until
    FROM (
      SELECT pg_catalog.max(a.attempted_at) AS oldest_attempt, pg_catalog.count(*) AS attempt_count
      FROM public.login_attempts AS a
      WHERE a.username = p_username AND a.attempted_at > v_now - interval '15 minutes'
      UNION ALL
      SELECT pg_catalog.max(a.attempted_at) AS oldest_attempt, pg_catalog.count(*) AS attempt_count
      FROM public.login_attempts AS a
      WHERE a.ip_address = p_ip_address AND a.attempted_at > v_now - interval '15 minutes'
    ) AS bucket
    WHERE bucket.attempt_count >= 5;

  RETURN QUERY
  SELECT
    COALESCE(v_lock_until > v_now, false),
    CASE WHEN v_lock_until > v_now
      THEN greatest(1, pg_catalog.ceil(extract(epoch FROM (v_lock_until - v_now)))::integer)
      ELSE 0
    END;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_login_failure(p_username text, p_ip_address text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_username IS NULL OR p_username !~ '^[a-z0-9_]{3,30}$' OR p_ip_address IS NULL OR pg_catalog.length(p_ip_address) > 45 THEN
    RAISE EXCEPTION 'Invalid login failure parameters' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  DELETE FROM public.login_attempts WHERE attempted_at < pg_catalog.clock_timestamp() - interval '24 hours';
  INSERT INTO public.login_attempts (username, ip_address, attempted_at)
  VALUES (p_username, p_ip_address, pg_catalog.clock_timestamp());
END;
$$;

CREATE OR REPLACE FUNCTION public.clear_login_attempts(p_username text, p_ip_address text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_username IS NULL OR p_username !~ '^[a-z0-9_]{3,30}$' OR p_ip_address IS NULL OR pg_catalog.length(p_ip_address) > 45 THEN
    RAISE EXCEPTION 'Invalid login cleanup parameters' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  DELETE FROM public.login_attempts
  WHERE username = p_username OR ip_address = p_ip_address OR attempted_at < pg_catalog.clock_timestamp() - interval '24 hours';
END;
$$;

