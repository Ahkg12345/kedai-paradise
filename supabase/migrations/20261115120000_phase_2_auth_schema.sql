CREATE OR REPLACE FUNCTION public.can_access_transaction(p_transaction_id integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.transactions AS t
    WHERE t.transaction_id = p_transaction_id
      AND (
        (SELECT public.current_user_role()) = 'admin'
        OR ((SELECT public.current_user_role()) = 'cashier' AND t.order_date = pg_catalog.timezone('Asia/Jakarta', now())::date)
      )
  )
$$;

